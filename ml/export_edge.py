"""
ml/export_edge.py
-----------------
Export the trained EdgeMLP + feature scaler + Mahalanobis profiles as a C header
(firmware/esp32_receiver/src/phyauth_model.h) for on-chip authentication.

No TensorFlow / TFLite toolchain is needed: the network is 11 -> 32 -> 16 and
pa_embed() in phyauth_dsp.c implements it directly (float32, ~1k MACs, a few
hundred microseconds on the ESP32 including feature extraction).
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Iterable, Optional

import numpy as np
import torch

import config
from dsp.pulse_dsp import FEATURE_NAMES, NUM_FEATURES
from ml.train import BUNDLE_FILE, MODEL_FILES


def _flit(v: float) -> str:
    """C float literal; "1f" is not valid C, "1.0f" is."""
    t = f"{float(v):.9g}"
    if not any(ch in t for ch in ".eEn"):
        t += ".0"
    return t + "f"


def _arr(name: str, values: Iterable[float], ctype: str = "float", per_line: int = 8) -> str:
    vals = [_flit(v) if ctype == "float" else str(v) for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n  ".join(lines)
    return f"static const {ctype} {name}[] = {{\n  {body}\n}};\n"


def _parse_code(code: str):
    if not code or "/" not in code:
        return 0, 0
    hexpart, nbits = code.split("/", 1)
    return int(hexpart, 16), int(nbits)


def build_header(ckpt_dir: Path = config.CHECKPOINT_DIR,
                 device_codes: Optional[Dict[str, str]] = None,
                 authorized: Optional[Iterable[str]] = None) -> Dict:
    bundle = json.loads((Path(ckpt_dir) / BUNDLE_FILE).read_text())
    ck = torch.load(Path(ckpt_dir) / MODEL_FILES["edge"], map_location="cpu", weights_only=True)
    sd = ck["state_dict"]
    w1, b1 = sd["fc1.weight"].numpy(), sd["fc1.bias"].numpy()
    w2, b2 = sd["fc2.weight"].numpy(), sd["fc2.bias"].numpy()
    h1, nf = w1.shape
    emb = w2.shape[0]
    assert nf == NUM_FEATURES, "feature count mismatch between model and DSP"

    prof = bundle["auth"]["edge"]["profiles"]
    codes = dict(bundle.get("device_codes", {}))
    codes.update({k: v for k, v in (device_codes or {}).items() if v})
    devs = [d for d in bundle["classes"] if d in prof and (authorized is None or d in set(authorized))]
    if not devs:
        raise ValueError("no authorized enrolled devices to export")

    cent = np.concatenate([np.asarray(prof[d]["centroid"], np.float32) for d in devs])
    covi = np.concatenate([np.asarray(prof[d]["cov_inv"], np.float32).ravel() for d in devs])
    thr = [prof[d]["threshold"] for d in devs]
    live = bundle.get("liveness", {})
    live_on = [1 if live.get(d, {}).get("active") else 0 for d in devs]
    live_mu = [live.get(d, {}).get("median_ppm", 0.0) if on else 0.0 for d, on in zip(devs, live_on)]
    live_tol = [live.get(d, {}).get("tolerance_ppm", 0.0) if on else 0.0 for d, on in zip(devs, live_on)]
    parsed = [_parse_code(codes.get(d, "")) for d in devs]

    version = f"{bundle.get('version', 'unknown')}"
    mean = np.asarray(bundle["scaler"]["mean"], np.float32)
    std = np.asarray(bundle["scaler"]["std"], np.float32)

    out = [
        "/*",
        " * phyauth_model.h - GENERATED by ml/export_edge.py, do not edit by hand.",
        f" * Generated : {datetime.now().isoformat(timespec='seconds')}",
        f" * Model     : EdgeMLP {nf}->{h1}->{emb}, bundle {version}",
        f" * Devices   : {', '.join(devs)}",
        " * Features  : " + ", ".join(FEATURE_NAMES),
        " */",
        "#ifndef PHYAUTH_MODEL_H",
        "#define PHYAUTH_MODEL_H",
        "#include <stdint.h>",
        "#define PHYAUTH_MODEL_PRESENT 1",
        f'#define PA_MODEL_VERSION "{version}"',
        f"#define PA_H1 {h1}",
        f"#define PA_EMB {emb}",
        f"#define PA_NDEV {len(devs)}",
        f"#define PA_BURST_FRAMES {config.BURST_DECISION_FRAMES}",
        "",
        _arr("PA_FEAT_MEAN", mean),
        _arr("PA_FEAT_STD", std),
        _arr("PA_W1", w1.ravel()),
        _arr("PA_B1", b1),
        _arr("PA_W2", w2.ravel()),
        _arr("PA_B2", b2),
        "static const char *const PA_DEV_ID[PA_NDEV] = {" + ", ".join(f'"{d}"' for d in devs) + "};",
        "static const uint64_t PA_DEV_CODE[PA_NDEV] = {" + ", ".join(f"0x{c:x}ULL" for c, _ in parsed) + "};",
        "static const int PA_DEV_NBITS[PA_NDEV] = {" + ", ".join(str(n) for _, n in parsed) + "};",
        _arr("PA_CENTROID", cent),
        _arr("PA_COVINV", covi),
        _arr("PA_THRESH", thr),
        "// Start-up drift liveness (ml/liveness.py): active, median and tolerance in ppm",
        "#define PA_HAS_LIVENESS 1",
        _arr("PA_LIVE_ON", live_on, ctype="int"),
        _arr("PA_LIVE_MU", live_mu),
        _arr("PA_LIVE_TOL", live_tol),
        "#endif",
        "",
    ]
    text = "\n".join(out)
    n_params = w1.size + b1.size + w2.size + b2.size
    flash_bytes = 4 * (n_params + mean.size + std.size + cent.size + covi.size + len(thr))
    return {"text": text, "version": version, "devices": devs,
            "liveness": {d: bool(on) for d, on in zip(devs, live_on)},
            "codes": {d: codes.get(d, "") for d in devs},
            "parameters": int(n_params), "flash_bytes": int(flash_bytes)}


def export_header(path: Path = config.EDGE_HEADER_PATH, **kw) -> Dict:
    info = build_header(**kw)
    Path(path).write_text(info["text"])
    info["path"] = str(path)
    return info
